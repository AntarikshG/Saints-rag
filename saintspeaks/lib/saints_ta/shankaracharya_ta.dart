        body: 'விடுதலை (மோக்ஷா) அடைய வேண்டிய ஒன்று அல்ல; அது உணர வேண்டியது. நாம் ஏற்கனவே விடுவிக்கப்பட்டவர்கள்; அறியாமை மட்டுமே நம்மை கட்டுப்படுத்தியதாக தோற்றமளிக்கிறது. விடுதலைக்கான பாதை அறியாமையை அறிவால் (ஞானம்) அகற்றுவது.\n\nமரபான பாதை மூன்று படிகளைக் கொண்டது: உண்மையை கேட்பது (ஸ்ரவணம்), அதை சிந்திப்பது (மனனம்), மற்றும் அதில் தியானிப்பது (நிதித்யாஸனம்). இந்த செயல்முறையின் மூலம் உண்மை நேரடி அனுபவமாக மாறுகிறது.\n\nஉண்மை மற்றும் பொய்யை வேறுபடுத்துதல் (விவேகம்) அவசியம். நாம் சுயம் மற்றும் அசுயம், நித்தியம் மற்றும் தற்காலிகம், விழிப்புணர்வு மற்றும் அதன் உள்ளடக்கங்களை வேறுபடுத்த கற்றுக்கொள்ள வேண்டும்.\n\nவெறுப்பு (வைராக்யம்) விவேகத்தைத் தொடர்ந்து வருகிறது. உலகியல் இன்பங்களின் தற்காலிக இயல்பை நாம் உண்மையாக புரிந்துகொள்ளும் போது, பற்று இயல்பாக விழுகிறது.\n\nஆன்மீக பயிற்சிக்கான நான்கு தகுதிகள்: விவேகம், வைராக்யம், ஆறு நற்பண்புகள் (அமைதி மற்றும் சுய கட்டுப்பாடு உள்ளிட்டவை), மற்றும் விடுதலைக்கான தீவிர விருப்பம். இந்த தகுதிகளுடன் மற்றும் குருவின் அருளுடன், விடுதலை உறுதி.'
